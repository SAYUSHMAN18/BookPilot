const fs = require("fs");
const path = require("path");
const { Pool } = require("pg");

// Postgres (via `pg`, the standard node-postgres driver) — replaced
// node:sqlite's DatabaseSync here so this app can run on Google Cloud Run,
// which scales to multiple stateless container instances with no shared
// local disk; a single SQLite file can't be safely written by more than
// one process at a time, and Cloud Run's own local disk is ephemeral
// (wiped on every restart/redeploy/scale event) regardless. Local dev and
// the test suite run against a real local Postgres too (docker-compose.yml,
// `postgres:16-alpine`) — deliberately not a SQLite-for-tests/Postgres-
// for-prod split, since tests passing against a different engine than
// production runs wouldn't actually prove the production code path works.
//
// DATA_DIR is unrelated to the database itself now (it used to point at
// the SQLite file's directory) — kept only because src/infra/uploads.js
// still uses it for locally-stored business photo uploads. That's its own
// separate Cloud-Run-ephemeral-disk problem (uploaded photos need to move
// to Cloud Storage for a real deployment), not addressed here.
const DATA_DIR = process.env.DATA_DIR || path.join(__dirname, "..", "..", "data");
fs.mkdirSync(DATA_DIR, { recursive: true });

if (!process.env.DATABASE_URL) {
  throw new Error(
    "DATABASE_URL is not set — see .env.example (DATABASE_URL=postgres://... , matches docker-compose.yml for local dev)."
  );
}
const pool = new Pool({ connectionString: process.env.DATABASE_URL });
// An idle connection in the pool can be dropped by the server (network
// blip, Postgres restart) at any moment with no query in flight — `pg`
// emits that as an 'error' event on the pool itself, which Node treats as
// an uncaught exception if nothing is listening (this app's own
// process.on('uncaughtException') crash-safety net would then take the
// whole process down over a single reconnectable connection hiccup).
pool.on("error", (err) => {
  require("../infra/logger").log("ERROR", `Postgres pool error: ${err.message}`);
});

// Thin convenience wrapper every store module builds on — kept minimal
// (no query builder, no ORM) to match this codebase's existing "no heavy
// deps" philosophy, the same reasoning that chose node:sqlite over
// better-sqlite3 and hand-rolled auth over jsonwebtoken/bcrypt. Returns
// just the rows array, since that's what every call site actually wants.
async function query(sql, params) {
  const result = await pool.query(sql, params);
  return result.rows;
}

// For a future column addition (not needed for the schema below, which is
// already the full current shape — see the migration this file replaced
// for the history that used to require this). Postgres supports `ADD
// COLUMN IF NOT EXISTS` directly, so unlike the old SQLite version (which
// had to manually check PRAGMA table_info() first), this is a one-liner.
async function ensureColumn(table, column, type, defaultSql) {
  const defaultClause = defaultSql !== undefined ? ` DEFAULT ${defaultSql}` : "";
  await pool.query(`ALTER TABLE ${table} ADD COLUMN IF NOT EXISTS ${column} ${type}${defaultClause}`);
}

// Runs the full schema, idempotently — safe to call on every process
// boot (both server.js and marketingServer.js call this once before
// listening). CREATE TABLE/INDEX/TRIGGER all use IF NOT EXISTS or
// CREATE-OR-REPLACE-equivalent guards, matching the old SQLite version's
// own idempotency, just without needing to replay every historical
// migration step — this is a fresh Postgres schema, not an in-place
// upgrade of existing SQLite data, so it's written directly in its final
// shape (every column the old ensureColumn() calls used to backfill is
// just part of the CREATE TABLE below).
//
// Timestamp columns use BIGINT, not INTEGER — every one of them stores
// Date.now() (epoch milliseconds), which is already ~1.7 trillion today,
// far past a 4-byte INTEGER's ~2.1 billion range. SQLite's dynamically-
// sized INTEGER type hid this; Postgres's fixed 4-byte INTEGER would
// silently overflow. Small bounded counts (nights, rating, attempts) stay
// INTEGER. Former "0/1 flag" columns (bookings.alerted_next,
// customer_preferences.alerts_opted_out, users.active,
// support_requests.resolved) are real BOOLEAN now — the store layer no
// longer needs `!!row.x` conversions for these (Stage 2).
async function runMigrationsBody() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS tenants (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      slug TEXT NOT NULL UNIQUE,
      plan TEXT NOT NULL DEFAULT 'free',
      status TEXT NOT NULL DEFAULT 'active' CONSTRAINT tenants_status_check CHECK (status IN ('awaiting_payment', 'onboarding_pending', 'onboarding_in_progress', 'pending', 'active', 'suspended', 'cancelled')),
      billing_email TEXT,
      branding_json TEXT,
      feature_flags_json TEXT,
      whatsapp_phone_number_id TEXT UNIQUE,
      whatsapp_business_account_id TEXT,
      whatsapp_access_token_encrypted TEXT,
      groq_api_key_encrypted TEXT,
      created_at BIGINT NOT NULL
    );
  `);
  const defaultTenantExists = (await query("SELECT 1 FROM tenants WHERE id = 1"))[0];
  if (!defaultTenantExists) {
    await pool.query(
      "INSERT INTO tenants (id, name, slug, plan, status, created_at) VALUES (1, 'Default', 'default', 'free', 'active', $1)",
      [Date.now()]
    );
  }
  // GENERATED BY DEFAULT AS IDENTITY's sequence doesn't know about the
  // explicit id=1 insert above — without this, the next auto-generated
  // tenant insert would also try id=1 and collide. Safe to run every
  // boot: keeps the sequence in sync with the real max id regardless of
  // whether this boot just inserted the default tenant or not.
  await pool.query(`SELECT setval(pg_get_serial_sequence('tenants', 'id'), COALESCE((SELECT MAX(id) FROM tenants), 1));`);

  // Widens tenants_status_check to the subscription-gated onboarding
  // sequence (awaiting_payment -> onboarding_pending -> onboarding_in_progress
  // -> active). CREATE TABLE IF NOT EXISTS above only sets this for a
  // brand-new table — an already-existing tenants table (this local dev DB
  // included) keeps whatever CHECK it was created with until explicitly
  // altered. Safe to run every boot: DROP...IF EXISTS is a no-op once
  // already renamed, ADD CONSTRAINT always reflects the current full list.
  await pool.query(`ALTER TABLE tenants DROP CONSTRAINT IF EXISTS tenants_status_check;`);
  try {
    await pool.query(`
      ALTER TABLE tenants ADD CONSTRAINT tenants_status_check
      CHECK (status IN ('awaiting_payment', 'onboarding_pending', 'onboarding_in_progress', 'pending', 'active', 'suspended', 'cancelled'));
    `);
  } catch (err) {
    // Found live (audit pass) — unlike CREATE OR REPLACE TRIGGER further
    // down, Postgres has no atomic "add or replace" for a CHECK
    // constraint: DROP...IF EXISTS + ADD is two round-trips, so two
    // processes booting at the same moment (this session's own rapid
    // restarts, or Cloud Run legitimately starting multiple instances
    // together) can both pass the DROP, then race on the ADD — whichever
    // runs second hits 42710 (duplicate_object) even though the
    // constraint it wanted now exists with the exact right definition
    // either way. Swallow only that specific, already-safe outcome —
    // anything else still crashes the boot as before.
    if (err.code !== "42710") throw err;
  }

  await pool.query(`
    CREATE TABLE IF NOT EXISTS bookings (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id INTEGER NOT NULL DEFAULT 1,
      wa_id TEXT NOT NULL,
      booking_id TEXT NOT NULL,
      booking_code TEXT,
      workflow_id TEXT NOT NULL,
      provider_id TEXT,
      provider_name TEXT,
      hotel_id TEXT,
      hotel_name TEXT,
      visit_date TEXT,
      visit_date_label TEXT,
      visit_time TEXT,
      check_in_iso TEXT,
      nights INTEGER,
      customer_name TEXT,
      age TEXT,
      gender TEXT,
      reason TEXT,
      status TEXT NOT NULL DEFAULT 'booked',
      cancelled_by TEXT,
      rescheduled_date TEXT,
      rescheduled_time TEXT,
      reschedule_note TEXT,
      alerted_next BOOLEAN,
      provider_note TEXT,
      feedback_requested_at BIGINT,
      payment_status TEXT,
      reminder_24h_sent_at BIGINT,
      reminder_2h_sent_at BIGINT,
      created_at BIGINT NOT NULL
    );
  `);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_bookings_wa_id ON bookings(wa_id);`);

  // The double-booking guarantee: Postgres refuses a second non-cancelled
  // row for the same (workflow_id, provider_id, visit_date, visit_time),
  // full stop — a partial unique index, translates directly from the old
  // SQLite version with no behavior change.
  await pool.query(`
    CREATE UNIQUE INDEX IF NOT EXISTS idx_no_double_slot
    ON bookings(workflow_id, provider_id, visit_date, visit_time)
    WHERE status != 'cancelled' AND visit_time IS NOT NULL AND visit_date IS NOT NULL;
  `);

  // Hotel date-range overlap check — SQLite did this as an inline
  // BEFORE INSERT trigger body; Postgres triggers need a separate
  // function. `provider_id IS NEW.provider_id` (SQLite's null-safe
  // equality) becomes `IS NOT DISTINCT FROM`; `date(x, '+N days')`
  // becomes `x::date + (n || ' days')::interval`. Kept as
  // `RAISE EXCEPTION 'HOTEL_RANGE_CONFLICT'` with the same literal message
  // bookingStore.js already matches on, so that call site's error
  // handling barely changes in Stage 2 (just message vs. code matching).
  await pool.query(`
    CREATE OR REPLACE FUNCTION check_hotel_range_overlap() RETURNS TRIGGER AS $$
    BEGIN
      IF NEW.check_in_iso IS NOT NULL AND NEW.nights IS NOT NULL AND NEW.status != 'cancelled' THEN
        IF EXISTS (
          SELECT 1 FROM bookings
          WHERE workflow_id = NEW.workflow_id
            AND provider_id IS NOT DISTINCT FROM NEW.provider_id
            AND check_in_iso IS NOT NULL AND nights IS NOT NULL
            AND status != 'cancelled'
            AND check_in_iso::date < (NEW.check_in_iso::date + (NEW.nights || ' days')::interval)
            AND NEW.check_in_iso::date < (check_in_iso::date + (nights || ' days')::interval)
        ) THEN
          RAISE EXCEPTION 'HOTEL_RANGE_CONFLICT';
        END IF;
      END IF;
      RETURN NEW;
    END;
    $$ LANGUAGE plpgsql;
  `);
  // Found live (audit pass) — the previous DROP TRIGGER IF EXISTS + CREATE
  // TRIGGER as two separate statements has a real race window: two
  // processes booting at once (this session's own rapid restarts, or
  // Cloud Run legitimately starting multiple instances at the same time)
  // can both pass the DROP, then both attempt CREATE — whichever runs
  // second fails with "already exists" and crashes that instance's boot.
  // CREATE OR REPLACE TRIGGER (Postgres 14+, this project targets 16) is
  // one atomic statement instead of two, closing the gap entirely rather
  // than narrowing it.
  await pool.query(`
    CREATE OR REPLACE TRIGGER trg_no_hotel_range_overlap
    BEFORE INSERT ON bookings
    FOR EACH ROW
    EXECUTE FUNCTION check_hotel_range_overlap();
  `);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS blocked_slots (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id INTEGER NOT NULL DEFAULT 1,
      workflow_id TEXT NOT NULL,
      provider_id TEXT NOT NULL,
      date TEXT NOT NULL,
      time TEXT,
      end_time TEXT,
      reason TEXT,
      created_at BIGINT NOT NULL
    );
  `);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_blocked_provider_date ON blocked_slots(workflow_id, provider_id, date);`);
  // Hotel multi-night availability blocking — a block with end_date set is
  // a date-RANGE block (a room off-market for several nights: maintenance,
  // an owner-occupied stretch) rather than a single-day/time block. time/
  // end_time stay NULL on a range block (a stay has no time-of-day
  // granularity); a normal single-day block simply leaves end_date NULL —
  // that's exactly what distinguishes the two shapes at every read site
  // (see availabilityStore.js's isDayRangeBlocked/hotelRangeBlocksFor).
  await ensureColumn("blocked_slots", "end_date", "TEXT");

  await pool.query(`
    CREATE TABLE IF NOT EXISTS customer_preferences (
      wa_id TEXT PRIMARY KEY,
      alerts_opted_out BOOLEAN NOT NULL DEFAULT false,
      updated_at BIGINT NOT NULL
    );
  `);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS feedback (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id INTEGER NOT NULL DEFAULT 1,
      booking_id INTEGER NOT NULL,
      workflow_id TEXT,
      wa_id TEXT NOT NULL,
      rating INTEGER,
      comment TEXT,
      created_at BIGINT NOT NULL
    );
  `);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_feedback_booking ON feedback(booking_id);`);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS sessions (
      tenant_id INTEGER NOT NULL,
      wa_id TEXT NOT NULL,
      data TEXT NOT NULL,
      updated_at BIGINT NOT NULL,
      PRIMARY KEY (tenant_id, wa_id)
    );
  `);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS outbound_queue (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id INTEGER NOT NULL DEFAULT 1,
      wa_id TEXT NOT NULL,
      body TEXT NOT NULL,
      attempts INTEGER NOT NULL DEFAULT 0,
      max_attempts INTEGER NOT NULL DEFAULT 5,
      status TEXT NOT NULL DEFAULT 'pending',
      next_attempt_at BIGINT NOT NULL,
      last_error TEXT,
      created_at BIGINT NOT NULL
    );
  `);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_outbound_queue_pending ON outbound_queue(status, next_attempt_at);`);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS users (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      email TEXT NOT NULL UNIQUE,
      password_hash TEXT NOT NULL,
      role TEXT NOT NULL CHECK (role IN ('admin', 'provider', 'platform_admin')),
      name TEXT,
      workflow_id TEXT,
      provider_id TEXT,
      tenant_id INTEGER,
      active BOOLEAN NOT NULL DEFAULT true,
      created_at BIGINT NOT NULL
    );
  `);
  // MFA (TOTP) — a user's secret is stored encrypted (secretsEncryption.js,
  // the same AES-256-GCM column convention as a tenant's WhatsApp/Groq
  // secrets) and mfa_enabled only flips to true once the user has proven
  // they can actually generate a valid code with it (see routes/auth.js's
  // enable step) — setting the secret alone must never be enough to make
  // MFA load-bearing on login.
  await ensureColumn("users", "mfa_secret_encrypted", "TEXT");
  await ensureColumn("users", "mfa_enabled", "BOOLEAN NOT NULL", "false");
  // Email verification — a self-signed-up admin can already prove email
  // ownership via the signup OTP (signup_otps), but a user CREATED by an
  // admin for a teammate (POST /api/dashboard/users) never goes through
  // that OTP step, so there was previously no record of whether ANY
  // user's email has actually been confirmed reachable. email_verified_at
  // is set at signup time for the self-signup path (the OTP that already
  // ran IS the verification) and left NULL for an admin-created teammate
  // until they complete their own verify-email step.
  await ensureColumn("users", "email_verified_at", "BIGINT");

  await pool.query(`
    CREATE TABLE IF NOT EXISTS password_reset_tokens (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id INTEGER NOT NULL,
      token_hash TEXT NOT NULL,
      expires_at BIGINT NOT NULL,
      used_at BIGINT,
      created_at BIGINT NOT NULL
    );
  `);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_password_reset_tokens_hash ON password_reset_tokens(token_hash);`);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS signup_otps (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      email TEXT NOT NULL,
      code_hash TEXT NOT NULL,
      expires_at BIGINT NOT NULL,
      used_at BIGINT,
      created_at BIGINT NOT NULL
    );
  `);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_signup_otps_email ON signup_otps(email);`);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS auth_sessions (
      id TEXT PRIMARY KEY,
      user_id INTEGER NOT NULL,
      user_agent TEXT,
      created_at BIGINT NOT NULL,
      expires_at BIGINT NOT NULL,
      revoked_at BIGINT
    );
  `);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_auth_sessions_user ON auth_sessions(user_id);`);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS audit_log (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id INTEGER,
      actor_email TEXT NOT NULL,
      actor_role TEXT NOT NULL,
      action TEXT NOT NULL,
      detail TEXT,
      created_at BIGINT NOT NULL
    );
  `);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_audit_created_at ON audit_log(created_at);`);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS knowledge_documents (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id INTEGER NOT NULL DEFAULT 1,
      workflow_id TEXT NOT NULL,
      title TEXT NOT NULL,
      content TEXT NOT NULL,
      created_at BIGINT NOT NULL,
      updated_at BIGINT NOT NULL
    );
  `);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_knowledge_workflow ON knowledge_documents(workflow_id);`);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS workflow_templates (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      industry TEXT,
      description TEXT,
      definition TEXT NOT NULL,
      created_by TEXT,
      created_at BIGINT NOT NULL
    );
  `);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS tenant_workflows (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id INTEGER NOT NULL,
      workflow_id TEXT NOT NULL,
      definition TEXT NOT NULL,
      created_at BIGINT NOT NULL,
      updated_at BIGINT NOT NULL,
      UNIQUE(tenant_id, workflow_id)
    );
  `);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_tenant_workflows_tenant ON tenant_workflows(tenant_id);`);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS support_requests (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id INTEGER NOT NULL DEFAULT 1,
      wa_id TEXT NOT NULL,
      workflow_id TEXT,
      message TEXT NOT NULL,
      resolved BOOLEAN NOT NULL DEFAULT false,
      created_at BIGINT NOT NULL
    );
  `);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_support_requests_workflow ON support_requests(workflow_id);`);

  // Subscription-gated onboarding — one row per tenant, opened by the
  // Razorpay subscription webhook the moment payment succeeds (tenant
  // flips awaiting_payment -> onboarding_pending at the same time), closed
  // when the onboarding team marks it complete (tenant flips to active via
  // the existing PATCH /api/platform/tenants/:id/status). Same shape/
  // spirit as support_requests above — a real row a human works, not a
  // status flag with nothing behind it.
  await pool.query(`
    CREATE TABLE IF NOT EXISTS onboarding_requests (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id INTEGER NOT NULL,
      status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'in_progress', 'complete')),
      intake_json TEXT,
      assigned_to TEXT,
      first_contact_by BIGINT,
      contacted_at BIGINT,
      created_at BIGINT NOT NULL,
      completed_at BIGINT
    );
  `);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_onboarding_requests_tenant ON onboarding_requests(tenant_id);`);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_onboarding_requests_status ON onboarding_requests(status, created_at);`);

  // The plan-checkout counterpart of `payments` above — kept as its own
  // table rather than reusing `payments` because that table's booking_id
  // is NOT NULL (one row per booking payment attempt); a plan subscription
  // charge has no booking behind it at all. Same "one row per attempt, not
  // per tenant" shape for the same audit-trail reasoning.
  await pool.query(`
    CREATE TABLE IF NOT EXISTS subscription_orders (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id INTEGER NOT NULL,
      plan TEXT NOT NULL,
      amount INTEGER NOT NULL,
      currency TEXT NOT NULL DEFAULT 'INR',
      status TEXT NOT NULL DEFAULT 'created' CHECK (status IN ('created', 'paid', 'failed')),
      provider TEXT NOT NULL DEFAULT 'razorpay',
      provider_order_id TEXT,
      provider_payment_id TEXT,
      failure_reason TEXT,
      created_at BIGINT NOT NULL,
      updated_at BIGINT NOT NULL
    );
  `);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_subscription_orders_tenant ON subscription_orders(tenant_id);`);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_subscription_orders_order ON subscription_orders(provider_order_id);`);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS payments (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id INTEGER NOT NULL,
      booking_id INTEGER NOT NULL,
      amount INTEGER NOT NULL,
      currency TEXT NOT NULL DEFAULT 'INR',
      status TEXT NOT NULL DEFAULT 'created' CHECK (status IN ('created', 'paid', 'failed', 'refunded', 'partially_refunded')),
      provider TEXT NOT NULL DEFAULT 'razorpay',
      provider_order_id TEXT,
      provider_payment_id TEXT,
      refund_status TEXT,
      refund_amount INTEGER,
      failure_reason TEXT,
      created_at BIGINT NOT NULL,
      updated_at BIGINT NOT NULL
    );
  `);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_payments_booking ON payments(booking_id);`);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_payments_tenant ON payments(tenant_id);`);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_payments_order ON payments(provider_order_id);`);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS calendar_connections (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id INTEGER NOT NULL,
      workflow_id TEXT NOT NULL,
      provider_id TEXT NOT NULL,
      calendar_type TEXT NOT NULL CHECK (calendar_type IN ('google', 'outlook')),
      external_calendar_id TEXT,
      refresh_token_encrypted TEXT NOT NULL,
      access_token_encrypted TEXT,
      access_token_expires_at BIGINT,
      status TEXT NOT NULL DEFAULT 'connected' CHECK (status IN ('connected', 'needs_reconnect', 'disconnected')),
      last_synced_at BIGINT,
      created_at BIGINT NOT NULL
    );
  `);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_calendar_connections_provider ON calendar_connections(tenant_id, workflow_id, provider_id);`);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS calendar_event_links (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      booking_id INTEGER NOT NULL,
      calendar_connection_id INTEGER NOT NULL,
      external_event_id TEXT NOT NULL,
      created_at BIGINT NOT NULL
    );
  `);
  await pool.query(`CREATE UNIQUE INDEX IF NOT EXISTS idx_calendar_event_links_booking ON calendar_event_links(booking_id, calendar_connection_id);`);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS api_keys (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id INTEGER NOT NULL,
      name TEXT NOT NULL,
      key_prefix TEXT NOT NULL,
      key_hash TEXT NOT NULL,
      created_at BIGINT NOT NULL,
      last_used_at BIGINT,
      revoked_at BIGINT
    );
  `);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_api_keys_tenant ON api_keys(tenant_id);`);
  await pool.query(`CREATE UNIQUE INDEX IF NOT EXISTS idx_api_keys_hash ON api_keys(key_hash);`);
}

// Found live (audit pass) — two processes booting at the exact same
// moment (this project's own frequent local restarts, or Cloud Run
// legitimately starting multiple container instances together) both
// call runMigrationsBody() concurrently, and Postgres's own catalog-level
// concurrency control surfaces that as a real, crashing error — not
// always the same one: "already exists" on a DROP+CREATE pair, or even
// "tuple concurrently updated" on a plain CREATE OR REPLACE FUNCTION,
// confirmed live during this session's own restart testing. Patching
// individual statements (CREATE OR REPLACE TRIGGER instead of DROP+CREATE
// a few lines up, a try/catch around one CHECK constraint) closed the two
// specific races that had already been seen, but the "tuple concurrently
// updated" one proved the actual bug is systemic — any DDL statement
// here can in principle race another process's identical one. A single
// Postgres advisory lock held for the whole migration is the standard
// fix (the same pattern Rails/Flyway/golang-migrate all use): a second
// process's own lock acquisition below simply BLOCKS until the first is
// completely done, so its migration queries never start concurrently
// with anyone else's in the first place — closing the whole class of bug
// at once rather than chasing individual statements one crash at a time.
// A dedicated client (not pool.query) is required — advisory locks are
// tied to the specific backend/session that acquired them, so the lock
// and the unlock have to be the same physical connection; the ~450 lines
// of actual migration statements inside runMigrationsBody() are
// untouched and keep using the pool exactly as before, since serializing
// entry into that function is all a lock guards here.
const MIGRATION_LOCK_KEY = 847362951;
async function runMigrations() {
  const lockClient = await pool.connect();
  try {
    await lockClient.query("SELECT pg_advisory_lock($1)", [MIGRATION_LOCK_KEY]);
    await runMigrationsBody();
  } finally {
    await lockClient.query("SELECT pg_advisory_unlock($1)", [MIGRATION_LOCK_KEY]);
    lockClient.release();
  }
}

module.exports = { pool, query, ensureColumn, runMigrations, DATA_DIR };
